import { z } from "zod";
import { appConfig } from "../../config/app.config.js";

const { minContributionCents, maxContributionCents } = appConfig.funding;

export const createContributionBody = z.object({
  campaignId: z.uuid(),
  amountCents: z
    .number()
    .int()
    .min(minContributionCents, `The minimum contribution is $${minContributionCents / 100}.`)
    .max(maxContributionCents, `The maximum contribution is $${maxContributionCents / 100}.`),
  // Backer names are private unless the backer opts in
  isPublic: z.boolean().default(false),
  // Guests only: where to send the receipt. Optional, and never shown publicly
  guestEmail: z.email("Enter a valid email address.").trim().toLowerCase().max(254).optional(),
  // Generated by the app once per checkout; retries with the same key never create a second payment
  idempotencyKey: z.string().min(8).max(80),
});

export const confirmContributionBody = z.object({
  cardNumber: z.string().regex(/^[\d\s-]{12,23}$/, "Enter a card number."),
});
